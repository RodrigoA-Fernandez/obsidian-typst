import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from 'fs';

const WASM_FILES = [
    {
        src: 'node_modules/@myriaddreamin/typst-ts-web-compiler/pkg/typst_ts_web_compiler_bg.wasm',
        dest: 'typst_ts_web_compiler_bg.wasm',
    },
    {
        src: 'node_modules/@myriaddreamin/typst-ts-renderer/pkg/typst_ts_renderer_bg.wasm',
        dest: 'typst_ts_renderer_bg.wasm',
    },
];

function copyWasmFiles() {
    for (const { src, dest } of WASM_FILES) {
        if (fs.existsSync(src)) {
            fs.copyFileSync(src, dest);
            console.log(`[obsidian-typst] Copied ${src} → ${dest}`);
        } else {
            console.warn(`[obsidian-typst] WASM source not found: ${src}`);
        }
    }
}

const banner =
    `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
    banner: {
        js: banner,
    },
    entryPoints: ["main.ts"],
    bundle: true,
    external: [
        "obsidian",
        "electron",
        "@codemirror/autocomplete",
        "@codemirror/collab",
        "@codemirror/commands",
        "@codemirror/language",
        "@codemirror/lint",
        "@codemirror/search",
        "@codemirror/state",
        "@codemirror/view",
        "@lezer/common",
        "@lezer/highlight",
        "@lezer/lr",
        ...builtins],
    loader: {
        '.woff': 'dataurl',
        '.woff2': 'dataurl',
        '.ttf': 'dataurl',
        '.wasm': 'binary',
    },
    format: "cjs",
    target: "es2018",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    outfile: "main.js",
});

if (prod) {
    await context.rebuild();
    copyWasmFiles();
    fs.renameSync('main.css', 'styles.css');
    process.exit(0);
} else {
    copyWasmFiles();
    await context.watch();
}
